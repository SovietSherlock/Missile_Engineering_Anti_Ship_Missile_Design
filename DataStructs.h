#pragma once
#include <vector>
#include <cmath>

// ============================================================================
// Параметры расчёта
// ============================================================================
struct CalcParameters
{
    double dt;      // шаг по времени, с
    double r_por;   // пороговое значение расстояния между ракетой и целью, м
};

// ============================================================================
// Начальные условия
// ============================================================================
struct InitConditions
{
    // Цель
    double Theta_c0;   // угол направления вектора скорости цели, рад
    double v_c0;       // скорость цели, м/с
    double x_g_c0;     // координата цели, м
    double y_g_c0;     // координата цели, м

    // Носитель
    double Theta_n0;   // угол направления вектора скорости носителя, рад {если NaN, то равен Theta_r}
    double v_n0;       // скорость носителя, м/с
    double x_g_pusk;   // координата пуска (начальная координата носителя и ракеты), м
    double y_g_pusk;   // координата пуска (начальная координата носителя и ракеты), м

    // Ракета
    double Theta_r0;   // угол направления вектора скорости ракеты, рад {если NaN, то определяется методом наведения}
    double v_r0;       // скорость ракеты, м/с
};

// ============================================================================
// Ограничения
// ============================================================================
struct LimitConditions
{
    double n_ya_r_max;     // максимальная перегрузка ракеты
    double t_r_min;        // минимальное время полёта ракеты, с
    double t_r_max;        // максимальное время полёта ракеты, с

    double R_r_min;        // минимальная дальность полёта ракеты, м {NaN: не проверяется}
    double R_r_max;        // максимальная дальность полёта ракеты, м {NaN: не проверяется}
    double y_g_r_min;      // минимальная высота полёта ракеты, м {NaN: не проверяется}
    double y_g_r_max;      // максимальная высота полёта ракеты, м {NaN: не проверяется}
    double epsilon_nc_min; // минимальный угол наклона линии визирования носитель-цель, рад {NaN: не проверяется}
    double epsilon_nc_max; // максимальный угол наклона линии визирования носитель-цель, рад {NaN: не проверяется}
    double v_r_min;        // минимальная скорость ракеты, м/с
};

// ============================================================================
// Данные по цели, носителю и ракете (таблицы перегрузок)
// ============================================================================
struct C_Data
{
    std::vector<std::vector<double>> n_xa_c_potr; // тангенциальная перегрузка цели (таблица время-перегрузка)
    std::vector<std::vector<double>> n_ya_c_potr; // нормальная скоростная перегрузка цели
};

struct N_Data
{
    std::vector<std::vector<double>> n_xa_n_potr; // тангенциальная перегрузка носителя
    std::vector<std::vector<double>> n_ya_n_potr; // нормальная скоростная перегрузка носителя
};

struct R_Data
{
    std::vector<std::vector<double>> n_xa_r_potr; // тангенциальная перегрузка ракеты
};

// ============================================================================
// Методы наведения
// ============================================================================
enum class GuidanceMethod
{
    Null,                      // нет управления (полёт с нулевой перегрузкой)
    PurePursuit,               // метод чистой погони (самонаведение)
    DeviatedPursuit,           // метод погони с постоянным углом упреждения (самонаведение)
    ParallelNav,               // метод параллельного сближения (самонаведение)
    ProportionalNav_const,     // метод пропорционального сближения с постоянным коэфф. (самонаведение)
    ProportionalNav_var,       // метод пропорционального сближения с переменным коэфф. (самонаведение)
    BeamRiding_LineOfSight,    // метод совмещения (теленаведение)
    BeamRiding_ConstAlignment, // метод "С" (теленаведение)
    BeamRiding_Alignment,      // метод спрямления (теленаведение)
    EVT,                       // энергетически выгодная траектория
    Gorka                      // ЭВТ + программный манёвр "горка"
};

struct GuidanceMethod_Data
{
    GuidanceMethod Method; // метод наведения
    double phi_upr;        // угол упреждения, рад (для DeviatedPursuit, всегда положительный)
    double k;              // коэффициент пропорциональности (для ProportionalNav_const)
    double lambda;         // коэффициент пропорциональности (для ProportionalNav_var)
    double C;              // коэффициент в методе "С" (для BeamRiding_ConstAlignment)
    double m;              // коэффициент в методе спрямления (для BeamRiding_Alignment)
    double K_g;            // коэффициент компенсации веса (для EVT, K_g > 1)
};

// ============================================================================
// Параметры ракеты (для физической модели)
// ============================================================================
struct RocketParams
{
    double m_bch;   // масса БЧ, кг
    double m_oun;   // масса отсека управления и наведения, кг
    double m_np;    // масса несущих поверхностей, кг
    double d;       // диаметр, м
    double beta;    // коэффициент beta (из расчёта)

    double m_pn() const { return m_bch + m_oun + m_np; }
};

// ============================================================================
// Результаты расчёта траектории (одна точка по времени)
// ============================================================================
struct TrajectoryParameters
{
    // Время
    double t;

    // Цель
    double Theta_c, v_c, x_g_c, y_g_c, n_xa_c, n_ya_c;

    // Носитель
    double Theta_n, v_n, x_g_n, y_g_n, n_xa_n, n_ya_n;

    // Ракета
    double Theta_r, v_r, x_g_r, y_g_r, n_xa_r, n_ya_r;

    // Кинематика ракета-цель
    double r_rc, dot_r_rc, ddot_r_rc;
    double epsilon_rc, dot_epsilon_rc, ddot_epsilon_rc;

    // Кинематика носитель-ракета
    double r_nr, dot_r_nr, ddot_r_nr;
    double epsilon_nr, dot_epsilon_nr, ddot_epsilon_nr;

    // Кинематика носитель-цель
    double r_nc, dot_r_nc, ddot_r_nc;
    double epsilon_nc, dot_epsilon_nc, ddot_epsilon_nc;

    // Для теленаведения
    double Delta_r, dot_Delta_r, ddot_Delta_r;
    double epsilon_l, dot_epsilon_l, ddot_epsilon_l;

    // Физическая модель ракеты
    double mass_r;      // текущая масса ракеты, кг
    double P_r;         // тяга двигателя, Н
    bool mode1;         // true — первый режим (разгонный), false — второй (маршевый)
    double alpha_r;     // угол атаки, рад
    double delta_r;     // отклонение рулей, рад
    double dTheta_r_prog; // программное изменение угла (для горки)
};